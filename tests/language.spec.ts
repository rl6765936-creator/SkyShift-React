import { test, expect } from '@playwright/test';
test('Hebrew and English persist, mirror navigation, retain the brand and preserve status values', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'עברית', exact: true }).click();
  await expect(page.locator('html')).toHaveAttribute('dir', 'rtl');
  await expect(page.getByRole('heading', { name: 'הטיסה הבאה שלך במרחק לחיצה אחת' })).toBeVisible();
  await expect(page.locator('.brand').first()).toHaveText('SkyShift');
  await page.reload();
  await expect(page.locator('html')).toHaveAttribute('lang', 'he');
  await page.getByRole('link', { name: 'כניסה', exact: true }).click();
  await expect(page.getByLabel('כתובת אימייל')).toBeVisible();
  await page.getByRole('button', { name: 'English', exact: true }).click();
  await expect(page.locator('html')).toHaveAttribute('dir', 'ltr');
  await expect(page.getByLabel('Email address')).toBeVisible();
  const payload = btoa(JSON.stringify({ role: 'Manager', exp: Math.floor(Date.now()/1000)+3600 }));
  await page.addInitScript(({ token }) => sessionStorage.setItem('skyshift.session', JSON.stringify({ id: 1, name: 'Manager', email: 'manager@example.com', token })), { token: `test.${payload}.test` });
  await page.route('**/api/manager/vehicles', route => route.fulfill({ json: [{ id: 1, status: 'Available', isPersonalExperimental: false, createdAt: '2026-10-01T12:00:00Z' }] }));
  await page.goto('/manager/vehicles');
  await page.getByRole('button', { name: 'עברית', exact: true }).click();
  await page.getByRole('button', { name: 'שינוי מצב', exact: true }).click();
  await expect(page.locator('dialog option[value="Available"]')).toHaveText('פנוי');
  await expect(page.locator('dialog option[value="Retired"]')).toHaveText('הוצא משימוש');
  await page.getByRole('button', { name: 'ביטול', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth+1)).toBeTruthy();
  await page.screenshot({ path: 'test-results/manager-he-390.png', fullPage: true });
  await page.goto('/');
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ path: 'test-results/home-he-1440.png', fullPage: true });
});
